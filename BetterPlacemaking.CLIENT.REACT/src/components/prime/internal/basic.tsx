import { createElement, useRef, type ReactNode, type SVGProps } from "react";

/** Joins truthy class fragments (space separated strings are kept as-is). */
export function classNames(...parts: Array<string | false | null | undefined>): string {
  return parts.filter(Boolean).join(" ");
}

let uid = 0;
/** Stable auto id like PrimeNG's `pn_id_N` (used when the caller passes no id). */
export function useUniqueId(prefix = "pn_id_"): string {
  const ref = useRef<string | null>(null);
  if (ref.current === null) ref.current = `${prefix}${++uid}`;
  return ref.current;
}

/** Internal helper: PrimeNG renders `<p-xxx>` host elements; React 19 supports custom elements natively. */
export function host(tag: string, props: Record<string, unknown> | null, ...children: ReactNode[]) {
  return createElement(tag, props, ...children);
}

type IconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & { spin?: boolean };

