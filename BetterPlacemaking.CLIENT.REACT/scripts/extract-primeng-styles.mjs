// One-off/maintenance tool: extracts the per-component style sources (the `style`/`css`
// PrimeNG layers on top of @primeuix/styles, incl. the "For PrimeNG" additions) from an
// installed primeng package into scripts/primeng-styles.generated.mjs.
// Usage: node scripts/extract-primeng-styles.mjs [path/to/primeng/fesm2022]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(process.argv[2] ?? path.join(here, '../../BetterPlacemaking.CLIENT/node_modules/primeng/fesm2022'));
const files = ['button','card','panel','tag','message','badge','checkbox','inputtext','password','inputnumber','select','datepicker','toggleswitch','togglebutton','selectbutton','listbox','autocomplete','table','paginator','dialog','confirmdialog','toast','menu','splitter','tooltip','divider','progressbar','avatar','iconfield','inputicon','ripple','icons-baseicon','skeleton','progressspinner','inputgroup','inputgroupaddon','fluid','overlay','popover','chip','radiobutton','scroller','textarea'];

const imports = [];
const entries = [];
const pkg = JSON.parse(fs.readFileSync(path.join(dir, '../package.json'), 'utf8'));
for (const f of files) {
  const src = fs.readFileSync(path.join(dir, `primeng-${f}.mjs`), 'utf8');
  const cls = src.match(/class (\w+Style) extends BaseStyle \{([\s\S]*?)static ɵfac/);
  if (!cls) throw new Error('no style class in ' + f);
  const body = cls[2];
  const name = body.match(/name = '([^']+)'/)[1];
  const styleRef = body.match(/\bstyle = (\w+\$?\d*);/)?.[1];
  const cssRef = body.match(/\bcss = (\w+\$?\d*);/)?.[1];
  const imp = src.match(/import \{ style(?: as (style\$1))? \} from '(@primeuix\/styles\/[\w-]+)';/);
  const alias = `${f.replace(/\W/g, '_')}_upstream`;
  let pre = '';
  if (imp) {
    imports.push(`import { style as ${alias} } from '${imp[2]}';`);
    pre += `const ${imp[1] ?? 'style'} = ${alias};\n`;
  }
  const local = (v) => {
    if (!v) return 'undefined';
    const m = src.match(new RegExp('^const ' + v.replace('$', '\\$') + ' = /\\*css\\*/ `([\\s\\S]*?)\\n`;', 'm'));
    return m ? `/*css*/ \`${m[1]}\n\`` : v;
  };
  const styleExpr = styleRef ? local(styleRef) : 'undefined';
  const cssExpr = cssRef ? local(cssRef) : 'undefined';
  entries.push(`  ${JSON.stringify(name)}: (() => {\n${pre}    return { style: ${styleExpr}, css: ${cssExpr} };\n  })(),`);
}
const out = `// GENERATED by scripts/extract-primeng-styles.mjs from primeng ${pkg.version}. Do not edit.\n${imports.join('\n')}\n\nexport const primengStyles = {\n${entries.join('\n')}\n};\n`;
fs.writeFileSync(path.join(here, 'primeng-styles.generated.mjs'), out);
console.log('wrote', files.length, 'components from primeng', pkg.version);
