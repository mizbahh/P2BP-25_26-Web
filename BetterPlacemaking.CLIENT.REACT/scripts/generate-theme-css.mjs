// Generates src/theme/aura-cyan.css: the exact CSS PrimeNG (Angular) injects at runtime for the
// BetterPlacemaking preset (Aura + cyan primary), for every component the React app may render.
// It reproduces PrimeNG's own pipeline (primeng/base BaseStyle + config/basecomponent loaders):
//   @primeuix/styles/<component> (+ PrimeNG additions in primeng-styles.generated.mjs)
//   -> css`` (resolves dt()) -> Theme.transformCSS -> minifyCSS, and Theme.getCommon/getComponent for variables.
// Usage: npm run theme:generate   (THEME_DUMP=/path/out.json also dumps {id: css} for verification)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Theme, css as cssTag, dt } from '@primeuix/styled';
import { style as baseStyle } from '@primeuix/styles/base';
import { resolve, minifyCSS } from '@primeuix/utils';
import preset from '../src/theme/preset.ts';
import { primengStyles } from './primeng-styles.generated.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));

Theme.setTheme({ preset, options: { darkModeSelector: '.app-dark-mode' } });

// from primeng/base (BaseStyle): the non-themed `css` of the "base" style
const baseCss = `
.p-hidden-accessible {
    border: 0;
    clip: rect(0 0 0 0);
    height: 1px;
    margin: -1px;
    overflow: hidden;
    padding: 0;
    position: absolute;
    width: 1px;
}

.p-hidden-accessible input,
.p-hidden-accessible select {
    transform: scale(0);
}

.p-overflow-hidden {
    overflow: hidden;
    padding-right: dt('scrollbar.width');
}
`;

// BaseStyle.load
const load = (style, transform = (cs) => cs) => {
  const computed = transform(cssTag`${resolve(style, { dt })}`);
  return computed ? minifyCSS(computed) : '';
};
const loadStyle = (name, style) =>
  load(style, (cs = '') => Theme.transformCSS(`${name}-style`, `${cs}${cssTag`${''}`}`));

const sections = []; // {id, title, css}
const add = (id, title, css) => { if (css) sections.push({ id, title, css }); };

// ---- common (primeng ConfigService.loadCommonTheme) ----
const { primitive, semantic, global, style: globalStyleSrc } = Theme.getCommon('base');
add('primitive-variables', 'Primitive variables', load(primitive?.css));
add('semantic-variables', 'Semantic variables', load(semantic?.css));
add('global-variables', 'Global variables', load(global?.css));
add('global-style', 'Global style', load(baseStyle, (cs = '') => Theme.transformCSS('global-style', `${cs}${cssTag`${globalStyleSrc}`}`)));
add('base', 'Base (p-hidden-accessible, p-overflow-hidden)', load(baseCss));

// ---- components (order = requested order, then extras) ----
const order = [
  'button', 'card', 'panel', 'tag', 'message', 'badge', 'checkbox', 'inputtext', 'password', 'inputnumber',
  'select', 'datepicker', 'toggleswitch', 'togglebutton', 'selectbutton', 'listbox', 'autocomplete',
  'datatable', 'paginator', 'dialog', 'confirmdialog', 'toast', 'menu', 'splitter', 'tooltip', 'divider',
  'progressbar', 'avatar', 'iconfield', 'inputicon', 'inputgroup', 'inputgroupaddon', 'fluid', 'ripple',
  'baseicon', 'skeleton', 'progressspinner', 'overlay', 'popover', 'chip', 'radiobutton', 'virtualscroller', 'textarea',
];
for (const name of order) {
  const src = primengStyles[name];
  if (!src) throw new Error(`no style source for ${name}`);
  const { css: compCss, style: compStyle } = Theme.getComponent(name) ?? {};
  add(`${name}-variables`, `${name} variables`, load(compCss));
  if (src.css) add(name, `${name} (non-themed css)`, load(src.css));
  if (src.style) {
    add(`${name}-style`, `${name} style`,
      load(src.style, (cs = '') => Theme.transformCSS(`${name}-style`, `${cs}${cssTag`${compStyle}`}`)));
  }
}

if (process.env.THEME_DUMP) {
  fs.writeFileSync(process.env.THEME_DUMP, JSON.stringify(Object.fromEntries(sections.map((s) => [s.id, s.css]))));
}

// group headers per component: variables + style stay together under one comment banner
const banner = (t) => `/* ${'='.repeat(70)}\n * ${t}\n * ${'='.repeat(70)} */\n`;
let out = `/* GENERATED by scripts/generate-theme-css.mjs (npm run theme:generate). DO NOT EDIT.
 * PrimeNG 20.4 Aura preset, primary=cyan, dark mode selector: .app-dark-mode (set on <html>).
 * Requires root font-size 16px (rem based). */\n\n`;
let last = null;
for (const s of sections) {
  const group = s.id.replace(/-(variables|style)$/, '');
  if (group !== last) {
    out += `\n${banner(group.toUpperCase())}`;
    last = group;
  }
  out += `/* ${s.id} */\n${s.css}\n`;
}
const target = path.join(here, '../src/theme/aura-cyan.css');
fs.writeFileSync(target, out);
console.log(`wrote ${target} (${(out.length / 1024).toFixed(1)} KB, ${sections.length} style blocks)`);
